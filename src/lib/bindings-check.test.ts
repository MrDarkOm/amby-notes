import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterEach, beforeEach, describe, expect, it } from "vitest"
import { checkGeneratedBindings } from "../../scripts/check-bindings.mjs"

describe("checkGeneratedBindings", () => {
  let directory: string
  let targetPath: string
  let original: Buffer

  beforeEach(async () => {
    directory = await mkdtemp(join(tmpdir(), "amby-bindings-test-"))
    targetPath = join(directory, "bindings.ts")
    original = Buffer.from("// locally edited but current\nexport type Example = string\n")
    await writeFile(targetPath, original)
  })

  afterEach(async () => {
    await rm(directory, { recursive: true, force: true })
  })

  it("passes when dirty working bytes exactly match generated bytes", async () => {
    await expect(
      checkGeneratedBindings({ targetPath, generate: async () => Buffer.from(original) }),
    ).resolves.toBeUndefined()
    expect(await readFile(targetPath)).toEqual(original)
  })

  it("fails for stale generated bytes without changing the source", async () => {
    await expect(
      checkGeneratedBindings({
        targetPath,
        generate: async () => Buffer.from("// stale bindings\n"),
      }),
    ).rejects.toThrow("Generated IPC bindings are stale")
    expect(await readFile(targetPath)).toEqual(original)
  })

  it("leaves source bytes unchanged when the generator fails", async () => {
    await expect(
      checkGeneratedBindings({
        targetPath,
        generate: async () => Promise.reject(new Error("cargo failed")),
      }),
    ).rejects.toThrow("cargo failed")
    expect(await readFile(targetPath)).toEqual(original)
  })

  it("leaves source bytes unchanged when the generator process cannot start", async () => {
    await expect(
      checkGeneratedBindings({
        targetPath,
        generate: async () => Promise.reject(new Error("spawn cargo ENOENT")),
      }),
    ).rejects.toThrow("spawn cargo ENOENT")
    expect(await readFile(targetPath)).toEqual(original)
  })

  it("detects a concurrent source edit without overwriting the newer bytes", async () => {
    const newerBytes = Buffer.from("newer concurrent edit\n")
    await expect(
      checkGeneratedBindings({
        targetPath,
        generate: async () => {
          await writeFile(targetPath, newerBytes)
          return Buffer.from(original)
        },
      }),
    ).rejects.toThrow("SOURCE_CHANGED_DURING_CHECK")
    expect(await readFile(targetPath)).toEqual(newerBytes)
  })
})
